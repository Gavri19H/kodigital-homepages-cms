#!/usr/bin/env node
// Usage: node scripts/build-public-fonts.mjs <directory-with-fontsource-woff2-files>
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const sourceDir = process.argv[2];
if (!sourceDir) throw new Error("Usage: node scripts/build-public-fonts.mjs <woff2-directory>");

// The body uses regular Nunito Sans. The homepage hero and shared headings use Nunito 800.
const families = [
  { name: "Nunito Sans", weights: [400, 600, 700, 800], preload: 400 },
  { name: "Nunito", weights: [700, 800, 900], preload: 800 },
];
const files = [];
const preloadPaths = [];
const faces = [];

for (const { name, weights, preload } of families) {
  const slug = name.toLowerCase().replaceAll(" ", "-");
  for (const weight of weights) {
    const source = join(sourceDir, `${slug}-latin-${weight}-normal.woff2`);
    const bytes = readFileSync(source);
    if (bytes.toString("ascii", 0, 4) !== "wOF2") throw new Error(`Expected a WOFF2 font at ${source}`);
    const hash = createHash("sha256").update(bytes).digest("hex").slice(0, 16);
    const path = `/assets/fonts/${slug}-${weight}.${hash}.woff2`;
    files.push(`  ["${path}", "${bytes.toString("base64")}"],`);
    if (weight === preload) preloadPaths.push(path);
    faces.push(`@font-face{font-family:"${name}";font-style:normal;font-weight:${weight};font-display:swap;src:url("${path}") format("woff2")}`);
  }
}

const output = new URL("../src/public/assets/public-fonts.generated.ts", import.meta.url);
writeFileSync(output, `// Generated by scripts/build-public-fonts.mjs from the Latin WOFF2 subsets in
// @fontsource/nunito@5.3.0 and @fontsource/nunito-sans@5.3.0.
// Copyright 2014 The Nunito Project Authors (https://github.com/googlefonts/nunito)
// Copyright 2016 The Nunito Sans Project Authors (https://github.com/Fonthausen/NunitoSans)
// Both fonts use the SIL Open Font License 1.1 (OFL-1.1).
// License text: https://openfontlicense.org/open-font-license-official-text/

export const PUBLIC_FONT_PRELOAD_PATHS = ${JSON.stringify(preloadPaths)} as const;

export const PUBLIC_FONT_FACE_CSS = \`${faces.join("\n")}\`;

export const PUBLIC_FONT_FILES: ReadonlyMap<string, string> = new Map([
${files.join("\n")}
]);
`);
console.log(`Wrote ${files.length} fonts to ${output.pathname}`);
