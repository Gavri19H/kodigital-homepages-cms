// Selected-state markup over one question element's slice. `values` are the
// String() forms of the answered value (multi-select = every member —
// applySelectionClasses semantics).
function markSelectionInSlice(slice: string, values: readonly string[]): string {
  const escaped = values.map((v) => escapeHtml(v));
  let selectedAnOption = false;
  let out = slice.replace(/<(button|option)\b[^>]*?>/g, (tag, tagName: string) => {
    const choice = tag.match(/\bdata-lg-choice="([^"]*)"/);
    if (choice === null) return tag; // e.g. the B9 Other trigger — never a value
    const isOn = escaped.indexOf(choice[1] ?? "") !== -1;
    if (tagName === "option") {
      // §9.2: dropdowns select the REAL option; the disabled placeholder
      // loses its `selected` below so exactly one option is selected.
      if (!isOn) return tag;
      selectedAnOption = true;
      return `${tag.slice(0, tag.length - 1)} selected>`;
    }
    // applySelectionClasses mirror (P5 tail — kept in lockstep with the P5
    // S5c ADJ-R8 runtime fix): aria-checked true/false on EVERY choice of
    // the answered question, matching the SSR aria-checked="false" default
    // this is layered over; class also added on the match.
    let next = setTagAttr(tag, "aria-checked", isOn ? "true" : "false");
    if (isOn) {
      next = addClassToTag(next, "lg-selected");
      next = setTagAttr(next, "aria-checked", "true");
    }
    return next;
  });
  if (selectedAnOption) {
    out = out.replace('<option value="" disabled selected>', '<option value="" disabled>');
  }
  return out;
}

// Error-state markup over one question element's slice (setFieldError mirror):
// ERROR_CLASS on the field block (the hydration root) + aria-invalid on its
// data-lg-input inputs (the root itself may BE the input — renderTextInput
// hydrates the <input> directly).
function markErrorInSlice(slice: string): string {
  const rootEnd = slice.indexOf(">");
  if (rootEnd === -1) return slice;
  let root = slice.slice(0, rootEnd + 1);
  root = addClassToTag(root, "lg-error");
  if (/\bdata-lg-input\b/.test(root)) root = setTagAttr(root, "aria-invalid", "true");
  const rest = slice
    .slice(rootEnd + 1)
    .replace(/<(input|select|textarea)\b[^>]*?>/g, (tag) =>
      /\bdata-lg-input\b/.test(tag) ? setTagAttr(tag, "aria-invalid", "true") : tag,
    );
  return root + rest;
}

// Success-state markup: the `.lg-valid` chrome convention on the field block.
function markValidInSlice(slice: string): string {
  const rootEnd = slice.indexOf(">");
  if (rootEnd === -1) return slice;
  return addClassToTag(slice.slice(0, rootEnd + 1), "lg-valid") + slice.slice(rootEnd + 1);
}

