// ---------------------------------------------------------------------------
// §9.2 sim request block — typed parse
// ---------------------------------------------------------------------------

export const LEADGEN_PREVIEW_SIM_STATES = [
  "default",
  "selected",
  "error",
  "dependency",
  "validation_success",
  "validation_error",
] as const;

export type LeadgenPreviewSimState = (typeof LEADGEN_PREVIEW_SIM_STATES)[number];

export interface LeadgenPreviewSimRequest {
  state: LeadgenPreviewSimState;
  // null = the caller sent no answers object (distinct from an empty {} —
  // an empty object still opts into the answers-driven dependency basis,
  // matching the legacy `sample_answers: {}` behavior).
  answers: Record<string, unknown> | null;
  // §9.2 flow simulation: the answer sequence reduced later-entries-win into
  // an accumulated record by the handler.
  flow: Array<{ internal_field: string; value: unknown }>;
  // Accepted per the §9.2 body shape; a static server render cannot express
  // auto-advance (it is a BEHAVIOR) — it becomes live with the §9.1 runtime-
  // bundle-in-iframe leg (Slice D).
  auto_advance: boolean;
}

const DEFAULT_SIM: LeadgenPreviewSimRequest = {
  state: "default",
  answers: null,
  flow: [],
  auto_advance: false,
};

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

// Parse the request's `sim` block. Absent → the default sim. Any shape
// violation → a { field: message } error record for the handler's 400.
export function parsePreviewSim(
  raw: unknown,
): { sim: LeadgenPreviewSimRequest; error: Record<string, string> | null } {
  if (raw === undefined || raw === null) return { sim: DEFAULT_SIM, error: null };
  if (!isRecord(raw)) {
    return { sim: DEFAULT_SIM, error: { sim: "sim must be an object" } };
  }
  const out: LeadgenPreviewSimRequest = { ...DEFAULT_SIM, flow: [] };

  const state = raw["state"];
  if (state !== undefined && state !== null) {
    if (
      typeof state !== "string" ||
      !(LEADGEN_PREVIEW_SIM_STATES as readonly string[]).includes(state)
    ) {
      return {
        sim: DEFAULT_SIM,
        error: { "sim.state": `sim.state must be one of ${LEADGEN_PREVIEW_SIM_STATES.join("|")}` },
      };
    }
    out.state = state as LeadgenPreviewSimState;
  }

  const answers = raw["answers"];
  if (answers !== undefined && answers !== null) {
    if (!isRecord(answers)) {
      return { sim: DEFAULT_SIM, error: { "sim.answers": "sim.answers must be an object" } };
    }
    out.answers = answers;
  }

  const flow = raw["flow"];
  if (flow !== undefined && flow !== null) {
    if (!Array.isArray(flow)) {
      return { sim: DEFAULT_SIM, error: { "sim.flow": "sim.flow must be an array" } };
    }
    for (const step of flow) {
      // Defensive skip (the §12.11 cleanObject-drop discipline): a malformed
      // step contributes nothing rather than failing the whole preview.
      if (!isRecord(step)) continue;
      const field = step["internal_field"];
      if (typeof field !== "string" || field === "") continue;
      out.flow.push({ internal_field: field, value: step["value"] });
    }
  }

  out.auto_advance = raw["auto_advance"] === true;
  return { sim: out, error: null };
}

// ---------------------------------------------------------------------------
// answered predicate — runtime/dependencies.ts isAnswered mirror (read-only)
