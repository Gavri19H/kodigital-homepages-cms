// LeadGen Section preview — §9.2 (E5) sim parameterization support.
//
// Two responsibilities, both PURE (no DB, no I/O):
//   1. parsePreviewSim — the typed parse of the §9.2 `sim` request block
//      ({ state, answers, auto_advance, flow }).
//   2. applyPreviewSimMarkup — server-renders a sim state INTO the preset
//      markup so the Studio iframe shows the REAL runtime state (selected
//      classes, error markup, success markup) instead of the deleted
//      outer-iframe attribute hacks (09 §9.2: "All sims are SERVER-rendered
//      into the srcdoc").
//
// WHY A POST-RENDER TRANSFORM (documented choice, 09 §9.1): the shared preset
// renderer (components/presets.ts) is byte-frozen for the live /lg shell —
// its render signatures may not grow sim parameters. The presets cannot
// express selected/error state, so the sim pass rewrites the RENDERED string.
// This is safe because the markup is fully machine-generated by presets.ts:
// every attribute is double-quoted and every author value is escapeHtml-
// escaped (`<>&"` never appear raw inside attributes or text), so `<` / `>`
// are structural — a small balanced-tag scanner is exact, not heuristic.
//
// RUNTIME PARITY (read-only mirrors of src/public/leadgen/runtime/*):
//   selected   → runtime/render.ts applySelectionClasses: SELECTED_CLASS
//                ("lg-selected") + aria-checked="true" on the matching
//                [data-lg-choice], aria-checked="false" on all other choices.
//                NOTE: markSelectionInSlice is NOT a pure mirror — it
//                additionally special-cases <option> tags (toggling native
//                `selected`) to approximate native <select> display semantics,
//                which the runtime function never does. A dropdown's matching
//                <option> gains `selected` (placeholder loses it).
//   error      → runtime/render.ts setFieldError: the [data-lg-field] block
//                gains ERROR_CLASS ("lg-error"), its [data-lg-input] gains
//                aria-invalid="true", and the [data-lg-error-for] slot shows
//                the message — SHOWN, i.e. the `hidden` attribute presets.ts
//                autoErrorSlot renders it with is REMOVED (render.ts:243
//                toggleHidden), which upsertErrorMessage below now mirrors.
//                When the author placed no ValidationError slot, a slot in
//                renderValidationError's exact shape is injected after the
//                question block so the message is VISIBLE.
//   validation_success → the `.lg-valid` chrome convention (designs/
//                default-funnel/styles.ts colors it validation.successColor).
//   Message copy mirrors runtime/validation.ts verbatim.

