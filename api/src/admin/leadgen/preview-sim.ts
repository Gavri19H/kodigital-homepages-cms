// Elements presets.ts emits without a closing tag.
const VOID_TAGS = new Set(["input", "img", "br", "hr", "meta", "link", "source", "wbr"]);

interface Span {
  start: number;
  end: number;
}

// The [start, end) span of the element whose OPENING TAG contains `token`
// (an `attr="value"` string). Balanced-tag scan from the opening tag; null
// when the token is absent (e.g. the component was dependency-filtered out).
function elementSpan(html: string, token: string): Span | null {
  const at = html.indexOf(token);
  if (at === -1) return null;
  const start = html.lastIndexOf("<", at);
  if (start === -1) return null;
  let first = true;
  let depth = 0;
  for (const m of html.slice(start).matchAll(/<(\/?)([a-zA-Z][a-zA-Z0-9-]*)[^>]*?>/g)) {
    const end = start + (m.index ?? 0) + m[0].length;
    const isClose = m[1] === "/";
    const name = (m[2] ?? "").toLowerCase();
    const isVoid = !isClose && (VOID_TAGS.has(name) || m[0].endsWith("/>"));
    if (first) {
      if (isClose) return null; // defensive: token cannot sit in a close tag
      if (isVoid) return { start, end };
      depth = 1;
      first = false;
      continue;
    }
    if (isVoid) continue;
    depth += isClose ? -1 : 1;
    if (depth === 0) return { start, end };
  }
  return null; // defensive: unbalanced markup — leave the html untouched
}

// Append/extend the class attribute on ONE opening-tag string.
function addClassToTag(tag: string, cls: string): string {
  const m = tag.match(/\bclass="([^"]*)"/);
  if (m === null) return `${tag.slice(0, tag.length - 1)} class="${cls}">`;
  if (m[1] !== undefined && m[1].split(" ").indexOf(cls) !== -1) return tag;
  return tag.replace(m[0], `class="${m[1]} ${cls}"`);
}

// Set (replace-or-append) a double-quoted attribute on ONE opening-tag string.
// `name` is always a fixed literal (aria-*), never author data.
function setTagAttr(tag: string, name: string, value: string): string {
  const re = new RegExp(`\\b${name}="[^"]*"`);
  if (re.test(tag)) return tag.replace(re, `${name}="${value}"`);
  return `${tag.slice(0, tag.length - 1)} ${name}="${value}">`;
}

// Drop a BOOLEAN attribute (fixed literal, never author data) from ONE
// opening-tag string. Quoted attribute VALUES are masked out first so a
// `name` token sitting inside an author value (a placeholder, a style, an
// internal_field) can never be mistaken for the attribute itself — the same
// "every attribute is double-quoted" property the header relies on.
function dropBooleanTagAttr(tag: string, name: string): string {
  const masked = tag.replace(/"[^"]*"/g, (q) => " ".repeat(q.length));
  const hit = masked.match(new RegExp(`\\s${name}(?=[\\s>/])`));
  if (hit === null || hit.index === undefined) return tag;
  return tag.slice(0, hit.index) + tag.slice(hit.index + hit[0].length);
}

