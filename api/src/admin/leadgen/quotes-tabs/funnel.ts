  // §8.2 "every drag has a menu path": chip-up/chip-down are the a11y equivalent
  // of the cross-page MOVE drag (onDragUp's chip branch). Within a page they swap
  // adjacent slots; at a page boundary they ROLL OVER to the neighbouring page in
  // the SAME funnel (last slot + down -> first slot of the next page; first slot
  // + up -> last slot of the previous page). No-op only at the funnel's absolute
  // ends (first slot of the first page up / last slot of the last page down).
  function moveFunnelChip(chip, dir) {
    var f = funnelOfEl(chip); if (!f || !f.model) { return; }
    var pi = pageIndexOfEl(chip); if (pi < 0) { return; }
    var slotId = Number(chip.getAttribute('data-slot-id'));
    var page = f.model.pages[pi]; if (!page) { return; }
    var idx = -1; var i;
    for (i = 0; i < page.slots.length; i++) { if (page.slots[i].slot_id === slotId) { idx = i; break; } }
    if (idx < 0) { return; }
    var to = dir === 'up' ? idx - 1 : idx + 1;
    if (to >= 0 && to < page.slots.length) {
      var tmp = page.slots[idx]; page.slots[idx] = page.slots[to]; page.slots[to] = tmp;
      saveFunnel(f.model, chip);
      return;
    }
    // page-boundary roll-over within the same funnel
    var destPi = dir === 'up' ? pi - 1 : pi + 1;
    if (destPi < 0 || destPi >= f.model.pages.length) { return; } // funnel's absolute end
    var destPage = f.model.pages[destPi];
    var moved = page.slots.splice(idx, 1)[0];
    if (dir === 'up') { destPage.slots.push(moved); } else { destPage.slots.unshift(moved); }
    saveFunnel(f.model, chip);
  }
